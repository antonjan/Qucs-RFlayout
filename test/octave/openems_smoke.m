% Small end-to-end integration fixture: PEC microstrip line, not filter validation.
clear;
physical_constants;
unit = 1e-3;
FDTD = InitFDTD('NrTS', 4000, 'EndCriteria', 1e-4);
FDTD = SetGaussExcite(FDTD, 10e9, 10e9);
FDTD = SetBoundaryCond(FDTD, {'MUR','MUR','MUR','MUR','PEC','MUR'});
CSX = InitCSX();
mesh.x = -2:0.25:10;
mesh.y = unique([-3:0.25:3, -0.813, 0.813]);
mesh.z = unique([0:0.127:0.762, 1:0.25:4]);
CSX = DefineRectGrid(CSX, unit, mesh);
CSX = AddMaterial(CSX, 'RO4350B');
CSX = SetMaterialProperty(CSX, 'RO4350B', 'Epsilon', 3.66);
CSX = AddBox(CSX, 'RO4350B', 0, [-2,-3,0], [10,3,0.762]);
CSX = AddMetal(CSX, 'signal');
CSX = AddBox(CSX, 'signal', 10, [0,-0.813,0.762], [8,0.813,0.762]);
[CSX, port{1}] = AddLumpedPort(CSX, 5, 1, 50, [0,-0.813,0], [0,0.813,0.762], [0,0,1], true);
[CSX, port{2}] = AddLumpedPort(CSX, 5, 2, 50, [8,-0.813,0], [8,0.813,0.762], [0,0,1], false);
mkdir('solver');
WriteOpenEMS(fullfile(pwd(), 'solver', 'line.xml'), FDTD, CSX);
RunOpenEMS(fullfile(pwd(), 'solver'), 'line.xml', '--numThreads=1');
f = linspace(1e9, 18e9, 101);
port{1} = calcPort(port{1}, fullfile(pwd(), 'solver'), f, 'RefImpedance', 50);
port{2} = calcPort(port{2}, fullfile(pwd(), 'solver'), f, 'RefImpedance', 50);
s11 = port{1}.uf.ref ./ port{1}.uf.inc;
s21 = port{2}.uf.ref ./ port{1}.uf.inc;
assert(all(isfinite(s11)) && all(isfinite(s21)));
assert(any(abs(s21) > 0.1));
mkdir('results');
fid = fopen('results/reflection.s1p', 'w');
fprintf(fid, '# Hz S RI R 50\n');
fprintf(fid, '%e %e %e\n', [f; real(s11); imag(s11)]);
fclose(fid);
dlmwrite('results/transmission.csv', [f(:), real(s21(:)), imag(s21(:))], ',');
set(0, 'defaultaxesfontname', 'DejaVu Sans');
set(0, 'defaulttextfontname', 'DejaVu Sans');
figure('visible','off');
plot(f/1e9, 20*log10(abs(s11)), f/1e9, 20*log10(abs(s21)));
xlabel('Frequency (GHz)'); ylabel('S parameter (dB)'); grid on;
print('results/response.png', '-dpng');
disp('OPENEMS_SMOKE_OK');
